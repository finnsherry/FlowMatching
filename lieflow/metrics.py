"""
metrics
=======

Sample-based metrics to quantify how well a generated distribution matches a
target distribution on a Lie group or homogeneous space. All metrics are based
on the logarithmic distance `d(g, h) = ||log(g^{-1} h)||_w`, i.e. the weighted
norm of the components of the generator of the exponential curve connecting `g`
and `h`, which is also what the flow matching loss is based on. The matrix of
pairwise distances is computed by the `distance_matrix` method of the space.

Provides the following functions:
  1. `wasserstein`: Wasserstein-1 distance between two empirical distributions
  with the same number of samples.
  2. `precision_coverage`: mean nearest neighbour distances from generated to
  target samples (precision) and from target to generated samples (coverage).
  3. `compare`: compute all of the above metrics between two sets of samples.

The `evaluate` method of the models applies `compare` to samples generated by
the model. Since finite samples of the same distribution do not have zero
distance, one should compare against the metrics between two independent sets
of samples of the target distribution, which can be computed with `compare`.
"""

import torch
from scipy.optimize import linear_sum_assignment

from lieflow.groups import Group, HomogeneousSpace, MatrixGroup, PowerSpace


def wasserstein(D: torch.Tensor) -> float:
    """
    Compute the Wasserstein-1 distance between two empirical distributions with
    the same number of samples, given the matrix `D` of pairwise distances.
    """

    if D.shape[0] != D.shape[1]:
        raise ValueError(f"Need the same number of samples, but D has shape {tuple(D.shape)}!")
    D = D.cpu().numpy()
    rows, cols = linear_sum_assignment(D)
    return float(D[rows, cols].mean())


def precision_coverage(D: torch.Tensor) -> tuple[float, float]:
    """
    Compute the mean distance from every generated sample to the nearest target
    sample (precision), and from every target sample to the nearest generated
    sample (coverage), given the matrix `D` of pairwise distances between
    generated samples (rows) and target samples (columns).
    """
    return float(D.min(dim=1).values.mean()), float(D.min(dim=0).values.mean())


@torch.no_grad()
def compare(
    G: Group | MatrixGroup | HomogeneousSpace | PowerSpace,
    X: torch.Tensor,
    Y: torch.Tensor,
    w: torch.Tensor | None = None,
) -> dict[str, float]:
    """
    Compute the Wasserstein-1 distance, precision, and coverage between samples
    `X` and target samples `Y`.

    Args:
        `G`: space with a `distance_matrix` method, e.g. a `Group`,
        `MatrixGroup`, `HomogeneousSpace`, or `PowerSpace`.
        `X`: samples of shape [N, ...], e.g. generated by a model.
        `Y`: target samples of shape [N, ...].
      Optional:
        `w`: weights of the components of the generator, as in
        `LogarithmicDistance`. Defaults to all ones.
    """
    D = G.distance_matrix(X, Y, w)
    precision, coverage = precision_coverage(D)
    return {"W_1": wasserstein(D), "precision": precision, "coverage": coverage}
